import type { ValueFormat } from "@/domain/format";

/**
 * Metric Registry — the single official definition of every BIOMIE metric.
 * Components never compute formulas; they look up a key here and read the
 * value produced by the semantic layer (database functions).
 */
export interface MetricDefinition {
  key: string;
  name: string;
  description: string;
  source: string;
  formula: string;
  format: ValueFormat;
  dateDimension: string | null;
  filters: string[];
  dependencies: string[];
  version: number;
  owner: string;
  enabled: boolean;
  /** Higher is better? Drives delta coloring. */
  polarity: "up" | "down" | "neutral";
  /** Caveats / business-rule notes. */
  notes?: string;
}


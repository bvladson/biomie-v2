export const METRICS: Record<string, MetricDefinition> = Object.fromEntries(
  defs.map((d) => [d.key, d]),
);
export const METRIC_LIST = defs;

export function metric(key: string): MetricDefinition {
  const m = METRICS[key];
  if (!m) throw new Error(`Unknown metric: ${key}`);
  return m;
}
